function obterQuestoesConcilio(area, modulo) {

    if (!QUESTOES_CONCILIO[area]) {

        console.warn(
            "Área não encontrada no banco de questões:",
            area
        );

        return [];

    }

    if (!QUESTOES_CONCILIO[area][modulo]) {

        console.warn(
            "Módulo não encontrado no banco de questões:",
            modulo
        );

        return [];

    }

    return QUESTOES_CONCILIO[area][modulo];

}


// ======================================================
// 3. CONTAGEM DE QUESTÕES
// ======================================================

function contarQuestoesConcilio(area, modulo) {

    const questoes = obterQuestoesConcilio(area, modulo);

    return questoes.length;

}


